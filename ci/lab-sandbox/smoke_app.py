"""Write one app into a checkout of the lab output repository in the layout `containerizer org` produces
(<org>/<project>/<repo>/<component>/, gitops/flux, containerizer.json, sandbox/), generated by containerizer
itself from examples/ci-demo (static analysis only, no build), with the component image replaced by a local
image (default localhost/lab/smoke:1, built by smoke.sh; never pushed).

usage: python smoke_app.py <output-checkout> <git-url> [image] [app-name]
"""
import dataclasses
import json
import shutil
import sys
import tempfile
from pathlib import Path

import yaml

from containerizer import org
from containerizer.analyze import analyze_app
from containerizer.generate import generate_app, k8s_name
from containerizer.gitops import GitOpsOptions

root, git_url = Path(sys.argv[1]).resolve(), sys.argv[2]
image = sys.argv[3] if len(sys.argv) > 3 else "localhost/lab/smoke:1"
name = sys.argv[4] if len(sys.argv) > 4 else "smoke"
example = Path(__file__).resolve().parent / "ci-demo" if (Path(__file__).resolve().parent / "ci-demo").is_dir() else None
repo_root = Path(org.__file__).resolve().parent.parent
example = example or repo_root / "examples" / "ci-demo"
rel = f"lab/{org.NO_PROJECT}/{name}"
with tempfile.TemporaryDirectory(prefix="lab-smoke-") as tmp:
    src = Path(tmp) / name
    shutil.copytree(example, src)
    gitops = GitOpsOptions(git_url=git_url, branch="main", path=rel)
    a = analyze_app(src, Path(tmp) / "analyze", verify=False, registry="localhost/lab", gitops=gitops)
    keep, excluded = org.select_components(a, False)
    if not keep:
        sys.exit(f"no A-rated component in {example}: {excluded}")
    gen = Path(tmp) / "gen"
    generate_app(dataclasses.replace(a, components=keep), gen, registry="localhost/lab", gitops=gitops, tag="1")
    org._clean_generated(gen)
    org.gitops_kustomizations(gen)
    comps = []
    for c in keep:
        cn = k8s_name(c.name)
        for f in (gen / cn).rglob("*.yaml"):
            t = f.read_text()
            docs = [d for d in yaml.safe_load_all(t) if d]
            changed = False
            for d in docs:
                for ctr in (((d.get("spec") or {}).get("template") or {}).get("spec") or {}).get("containers") or []:
                    if ctr.get("name") == cn or len(keep) == 1:
                        ctr["image"], changed = image, True
            if changed:
                f.write_text("---\n".join(yaml.safe_dump(d, sort_keys=False) for d in docs))
        # kustomize `images:` entries would rewrite it again: drop them for this component
        kf = gen / "kustomization.yaml"
        if kf.exists():
            k = yaml.safe_load(kf.read_text())
            if k.get("images"):
                k["images"] = [i for i in k["images"] if cn not in i.get("name", "")] or None
                k = {x: y for x, y in k.items() if y is not None}
                kf.write_text(yaml.safe_dump(k, sort_keys=False))
        comps.append({"component": c.name, "folder": cn, "image": image, "rating": "A", "verdict": c.verdict,
                      "role": c.role, "project": c.project.rel, "project_name": c.project.name,
                      "verification": "not run"})
    dest = root / rel
    if dest.exists():
        shutil.rmtree(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(gen, dest)
    res = org.RepoResult(provider="lab", org="lab", project=org.NO_PROJECT, repo=name, status="deployed",
                         app=k8s_name(name), path=rel, rating=a.rating, components=comps, excluded=excluded)
    (dest / "containerizer.json").write_text(json.dumps(res.to_dict(), indent=2, default=str) + "\n")
ns = org.write_sandbox(root, git_url, "main")
print(f"{rel}: {', '.join(c['component'] for c in comps)} -> {image}; sandbox namespaces: {', '.join(ns)}")
