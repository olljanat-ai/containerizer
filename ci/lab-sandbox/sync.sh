#!/bin/bash
# What the appliance's cz-sandbox (appliance/rootfs/usr/lib/containerizer/bin/cz-sandbox) does every 2
# minutes, for the lab: the read-only Git token of the output repository in the secret store for Flux's
# root sync (flux-system--cz-git) and for every app (<namespace>--cz-git), the root GitRepository +
# Kustomization containerizer-sandbox (./sandbox/flux/apps), and, lab only, the read-only verifier of
# `containerizer sandbox verify` (sandbox/verify-rbac.yaml of the output repository, token kubeconfig).
# Run by the systemd timer lab-sandbox-sync.timer; safe to run by hand.
. "$(dirname "$0")/lib.sh"
have_cluster || { echo "lab sandbox: the cluster is not up (up.sh)" >&2; exit 0; }
cz_store_ready || exit 0
cz_store_setup
secrets
[ -n "${LAB_GIT_READ_TOKEN:-}" ] || { echo "no LAB_GIT_READ_TOKEN in $SECRETS (up.sh)" >&2; exit 1; }
k get crd gitrepositories.source.toolkit.fluxcd.io kustomizations.kustomize.toolkit.fluxcd.io >/dev/null 2>&1 || exit 0

# the token (read-only), and the lab CA: Flux takes ca.crt from the same Secret (the appliance's Git servers
# have public certificates, so there it is not needed)
git_token() { cz_store_put "$1" username="$GIT_ADMIN" password="$LAB_GIT_READ_TOKEN" ca.crt=@"$CA"; }

git_token flux-system--cz-git
cz_store_grant flux-system flux-system--cz-git
k apply -f - >/dev/null <<YAML
apiVersion: external-secrets.io/v1
kind: ExternalSecret
metadata:
  name: containerizer-sandbox-git
  namespace: flux-system
  labels: {app.kubernetes.io/part-of: containerizer-sandbox, app.kubernetes.io/managed-by: containerizer-appliance}
spec:
  refreshInterval: 1h
  secretStoreRef: {kind: ClusterSecretStore, name: app-secrets}
  target: {name: containerizer-sandbox-git, creationPolicy: Owner, deletionPolicy: Retain}
  dataFrom:
    - extract: {key: flux-system--cz-git}
---
apiVersion: source.toolkit.fluxcd.io/v1
kind: GitRepository
metadata:
  name: containerizer-sandbox
  namespace: flux-system
  labels: {app.kubernetes.io/part-of: containerizer-sandbox, app.kubernetes.io/managed-by: containerizer-appliance}
spec:
  interval: 5m
  url: ${GIT_URL}
  ref: {branch: main}
  secretRef: {name: containerizer-sandbox-git}
---
apiVersion: kustomize.toolkit.fluxcd.io/v1
kind: Kustomization
metadata:
  name: containerizer-sandbox
  namespace: flux-system
  labels: {app.kubernetes.io/part-of: containerizer-sandbox, app.kubernetes.io/managed-by: containerizer-appliance}
spec:
  interval: 10m
  retryInterval: 2m
  timeout: 5m
  prune: true
  wait: false
  sourceRef: {kind: GitRepository, name: containerizer-sandbox}
  path: ./sandbox/flux/apps
YAML
# every app GitRepository generated by containerizer for the lab repository gets the token it names
k get gitrepositories.source.toolkit.fluxcd.io -A -l app.kubernetes.io/managed-by=containerizer \
  -o jsonpath='{range .items[*]}{.metadata.namespace}{" "}{.spec.url}{" "}{.spec.secretRef.name}{"\n"}{end}' \
| while read -r ns url name; do
    [ "$url" = "$GIT_URL" ] && [ -n "$name" ] && [ "$ns" != flux-system ] || continue
    k -n "$ns" get externalsecrets.external-secrets.io "$name" >/dev/null 2>&1 || continue
    new=; k -n "$CZ_STORE_NS" get secret "$ns--cz-git" >/dev/null 2>&1 || new=1
    git_token "$ns--cz-git"
    # a new app: sync now rather than after ESO's back-off from the first, failed read
    [ -z "$new" ] || k -n "$ns" annotate --overwrite externalsecrets.external-secrets.io "$name" \
      "force-sync=$(date +%s)" >/dev/null
  done

# ---------------------------------------------------------------- the verifier (lab only)
# The output repository's sandbox/verify-rbac.yaml (read-only access to the app namespaces, no Secrets)
# applied as cluster admin, and a kubeconfig with a 24-hour token of that ServiceAccount, renewed after 12.
ro=$STATE/output-ro
hdr=$(git_header "$LAB_GIT_READ_TOKEN")
if [ -d "$ro/.git" ]; then
  git -C "$ro" -c "http.$GIT_URL.extraHeader=$hdr" fetch -q origin main && git -C "$ro" reset -q --hard origin/main
else
  git -c "http.$GIT_URL.extraHeader=$hdr" clone -q --branch main "$GIT_URL" "$ro"
fi
rbac=$ro/sandbox/verify-rbac.yaml
[ -f "$rbac" ] || exit 0
# The app namespaces must exist first (Flux creates them). The file also grants read access to the Argo CD
# Applications in namespace argocd: the lab runs Flux only, so that part is left out while there is no argocd.
existing=$(k get ns -o jsonpath='{.items[*].metadata.name}')
if ! "$PY" - "$rbac" "$existing" > "$STATE/verify-rbac.lab.yaml" <<'PY'
import sys, yaml
docs = [d for d in yaml.safe_load_all(open(sys.argv[1])) if d]
have = set(sys.argv[2].split()) | {d["metadata"]["name"] for d in docs if d["kind"] == "Namespace"}
missing = sorted({d["metadata"].get("namespace") for d in docs} - have - {None, "argocd"})
if missing:
    sys.exit(f"verifier: waiting for namespaces {' '.join(missing)}")
print("---\n".join(yaml.safe_dump(d) for d in docs if d["metadata"].get("namespace") in have | {None}))
PY
then exit 0; fi
k apply -f "$STATE/verify-rbac.lab.yaml" >/dev/null
read -r vns vsa < <("$PY" -c 'from containerizer import sandbox as s; print(s.VERIFIER_NS, s.VERIFIER)')
vk=$LAB_DIR/verifier.kubeconfig
if [ ! -s "$vk" ] || [ -n "$(find "$vk" -mmin +720)" ]; then
  tok=$(k -n "$vns" create token "$vsa" --duration=24h)
  server=$(k config view --minify -o jsonpath='{.clusters[0].cluster.server}')
  ca=$(k config view --raw --minify -o jsonpath='{.clusters[0].cluster.certificate-authority-data}')
  umask 077
  cat > "$vk.tmp" <<YAML
apiVersion: v1
kind: Config
clusters: [{name: lab, cluster: {server: "$server", certificate-authority-data: "$ca"}}]
users: [{name: $vsa, user: {token: "$tok"}}]
contexts: [{name: verifier, context: {cluster: lab, user: $vsa}}]
current-context: verifier
YAML
  mv "$vk.tmp" "$vk"
fi
