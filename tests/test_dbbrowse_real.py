"""The database browser's clients against the real servers: psql, mysql and sqlcmd in the lab's images, run
with `docker exec -i` through the same code path the agent uses with `kubectl exec -i` (dbbrowse.Target).

Skipped unless CONTAINERIZER_TEST_DB_CLIENTS=1 (needs Docker and the images postgres:18.6-alpine,
mysql:8.4.13 and mcr.microsoft.com/mssql/server:2025-latest, pulled when missing). Each engine's server is
provisioned the way the lab agent does it (labservices.provision_sql as the admin), then the app's own login
browses, edits and runs SQL, and the database is dropped as the admin with dbbrowse.drop_script.
"""
from __future__ import annotations

import os
import secrets
import subprocess
import time

import pytest

from containerizer import dbbrowse as D
from containerizer import labservices as L

pytestmark = pytest.mark.skipif(os.environ.get("CONTAINERIZER_TEST_DB_CLIENTS") != "1",
                                reason="set CONTAINERIZER_TEST_DB_CLIENTS=1 to run the clients against real servers")

NS = "parts-catalog-refactor-7"
IMAGES = {"postgres": "postgres:18.6-alpine", "mysql": "mysql:8.4.13",
          "sqlserver": "mcr.microsoft.com/mssql/server:2025-latest"}
ADMIN_PW = "Adm1n" + secrets.token_hex(8)


def _docker(*args, input=None, check=True, timeout=120):
    return subprocess.run(["docker", *args], input=input, capture_output=True, text=True, check=check, timeout=timeout)


def _start(engine: str) -> str:
    name = f"cz-dbb-test-{engine}-{secrets.token_hex(3)}"
    env = {"postgres": ["-e", f"POSTGRES_PASSWORD={ADMIN_PW}", "-e", "POSTGRES_HOST_AUTH_METHOD=scram-sha-256",
                        "-e", "POSTGRES_INITDB_ARGS=--auth-host=scram-sha-256 --auth-local=peer"],
           "mysql": ["-e", f"MYSQL_ROOT_PASSWORD={ADMIN_PW}", "-e", "MYSQL_ROOT_HOST=127.0.0.1"],
           "sqlserver": ["-e", "ACCEPT_EULA=Y", "-e", "MSSQL_PID=Developer", "-e", f"MSSQL_SA_PASSWORD={ADMIN_PW}"]}[engine]
    user = {"postgres": ["-u", "70:70"], "mysql": [], "sqlserver": []}[engine]
    _docker("run", "-d", "--name", name, *user, *env, IMAGES[engine], timeout=600)
    return name


def _admin(engine: str, name: str, script: str) -> subprocess.CompletedProcess:
    return subprocess.run(["docker", "exec", "-i", name, *L.provision_command(engine)], input=script,
                          capture_output=True, text=True, timeout=120)


def _wait(engine: str, name: str) -> None:
    probe = {"postgres": "SELECT 1;\n", "mysql": "SELECT 1;\n", "sqlserver": "SELECT 1;\nGO\n"}[engine]
    deadline = time.time() + 240
    while time.time() < deadline:
        if _admin(engine, name, probe).returncode == 0:
            if engine != "mysql":
                return
            # the image's entry point restarts the server after its first start
            time.sleep(3)
            if _admin(engine, name, probe).returncode == 0:
                return
        time.sleep(2)
    raise AssertionError(f"{engine} did not start: {_docker('logs', name, check=False).stdout[-2000:]}")


@pytest.fixture(scope="module", params=["postgres", "mysql", "sqlserver"])
def server(request):
    engine = request.param
    if _docker("image", "inspect", IMAGES[engine], check=False).returncode:
        _docker("pull", IMAGES[engine], timeout=900)
    name = _start(engine)
    try:
        _wait(engine, name)
        cred = L.new_credentials(engine, NS)
        p = _admin(engine, name, L.provision_sql(engine, NS, cred))
        assert p.returncode == 0, p.stderr + p.stdout
        seen = []

        def runner(argv, stdin, timeout=D.EXEC_TIMEOUT, cap=D.MAX_BYTES):
            seen.append(argv)
            return D.run_capped(argv, stdin, timeout, cap)
        target = D.Target(engine, ["docker", "exec", "-i", name], cred["username"], cred["database"], cred["password"], NS)
        yield engine, name, target, runner, seen, cred
    finally:
        _docker("rm", "-f", name, check=False)


def run(server, sql, max_rows=D.MAX_ROWS):
    engine, _, target, runner, _, _ = server
    return D.run_statement(target, sql, max_rows, runner)


DDL = {
    "postgres": "CREATE TABLE public.parts (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku varchar(40) NOT NULL, "
                "name text NOT NULL, price numeric(10,2), note text, created timestamp DEFAULT now(), img bytea)",
    "mysql": "CREATE TABLE parts (id int AUTO_INCREMENT PRIMARY KEY, sku varchar(40) NOT NULL, name text NOT NULL, "
             "price decimal(10,2), note text, created datetime DEFAULT CURRENT_TIMESTAMP, img varbinary(16))",
    "sqlserver": "CREATE TABLE dbo.Parts (Id int IDENTITY(1,1) PRIMARY KEY, Sku nvarchar(40) NOT NULL, Name nvarchar(max) NOT NULL, "
                 "Price decimal(10,2), Note nvarchar(200), Created datetime2(3) DEFAULT SYSUTCDATETIME(), Img varbinary(16), "
                 "Ver rowversion)",
}
TRICKY = ["O'Brien \\ back\\\\slash", "日本語 ✓ ünïcode", "100% _done_ [x] !bang", "line1\nline2\r\nline3", "--; DROP TABLE x; --",
          "$(MSSQL_SA_PASSWORD) :r /etc/passwd", "'; SELECT 1; --", "\\! id"]


def _names(engine):
    if engine == "sqlserver":
        return "dbo", "Parts", {"id": "Id", "sku": "Sku", "name": "Name", "price": "Price", "note": "Note", "blob": "Img"}
    return ("public" if engine == "postgres" else None), "parts", {k: k for k in ("id", "sku", "name", "price", "note", "img")} | {"blob": "img"}


def test_browse_edit_and_sql(server):
    engine, name, target, runner, seen, cred = server
    assert run(server, DDL[engine])["kind"] == "count"
    schema, table, n = _names(engine)
    tables = run(server, D.tables_sql(engine))
    assert tables["kind"] == "rows" and tables["columns"] == ["schema", "name", "kind", "rows"]
    assert [r[1] for r in tables["rows"]] == [table]
    schema = schema or tables["rows"][0][0]
    cols = D.parse_columns(run(server, D.columns_sql(engine, schema, table)))
    by = {c.name: c for c in cols}
    assert [c.name for c in D.primary_key(cols)] == [n["id"]] and by[n["id"]].auto
    assert not by[n["sku"]].nullable and by[n["note"]].nullable and D.is_binary(by[n["blob"]].type)
    assert D.read_only_reason(cols) is None
    if engine == "sqlserver":
        assert by["Ver"].generated and not by["Ver"].editable and by["Price"].type == "decimal(10,2)"

    # every tricky value goes in and comes back exactly
    for i, v in enumerate(TRICKY):
        r = run(server, D.insert_sql(engine, schema, table, cols, {n["sku"]: f"SKU-{i}", n["name"]: v, n["price"]: "12.50",
                                                                   n["note"]: None}))
        assert r == {"kind": "count", "rowcount": 1}, (v, r)
    page = run(server, D.rows_sql(engine, schema, table, cols, sort=n["sku"]))
    assert page["kind"] == "rows" and len(page["rows"]) == len(TRICKY)
    idx = {c.name: i for i, c in enumerate(cols)}
    got = [r[idx[n["name"]]] for r in page["rows"]]
    assert got == TRICKY
    assert all(r[idx[n["note"]]] is None for r in page["rows"])
    assert page["rows"][0][idx[n["price"]]] == "12.50"

    # filters: contains with wildcards and quotes taken literally, equals, NULL
    for needle, want in (("% _done_ [x] !", 1), ("o'brien", 1), ("\\\\", 1), ("DROP TABLE", 1), ("nothing", 0)):
        res = run(server, D.rows_sql(engine, schema, table, cols, filt=(n["name"], "contains", needle)))
        assert len(res["rows"]) == want, (needle, res)
    assert len(run(server, D.rows_sql(engine, schema, table, cols, filt=(n["sku"], "eq", "SKU-3")))["rows"]) == 1
    assert len(run(server, D.rows_sql(engine, schema, table, cols, filt=(n["note"], "null", "")))["rows"]) == len(TRICKY)
    assert len(run(server, D.rows_sql(engine, schema, table, cols, offset=5, limit=2))["rows"]) == 2

    # edit and delete by primary key
    first = page["rows"][0]
    key = {n["id"]: first[idx[n["id"]]]}
    assert run(server, D.update_sql(engine, schema, table, cols, key, {n["note"]: "it's \\ fine", n["price"]: None})) == \
        {"kind": "count", "rowcount": 1}
    row = run(server, D.row_sql(engine, schema, table, cols, key))["rows"][0]
    assert row[idx[n["note"]]] == "it's \\ fine" and row[idx[n["price"]]] is None
    assert run(server, D.delete_sql(engine, schema, table, cols, key)) == {"kind": "count", "rowcount": 1}
    assert run(server, D.delete_sql(engine, schema, table, cols, key)) == {"kind": "count", "rowcount": 0}
    blobq = {"postgres": "UPDATE parts SET img = '\\x00ff10'::bytea WHERE sku = 'SKU-1'",
             "mysql": "UPDATE parts SET img = X'00FF10' WHERE sku = 'SKU-1'",
             "sqlserver": "UPDATE dbo.Parts SET Img = 0x00FF10 WHERE Sku = N'SKU-1'"}[engine]
    assert run(server, blobq)["rowcount"] == 1
    got = run(server, D.rows_sql(engine, schema, table, cols, filt=(n["sku"], "eq", "SKU-1")))["rows"][0][idx[n["blob"]]]
    assert got.lower() in ("\\x00ff10", "0x00ff10")

    # free SQL: rows, counts, errors
    res = run(server, f"SELECT {n['sku']} AS s, NULL AS nothing, '' AS blank FROM {D.table_ref(engine, schema, table)} "
                      f"ORDER BY {n['sku']}")
    assert res["columns"] == ["s", "nothing", "blank"] and res["rows"][0] == ["SKU-1", None, ""]
    upd = run(server, f"UPDATE {D.table_ref(engine, schema, table)} SET {n['note']} = 'x'")
    assert upd == {"kind": "count", "rowcount": len(TRICKY) - 1}
    with pytest.raises(D.DbError) as ex:
        run(server, "SELECT * FROM no_such_table")
    assert "no_such_table" in str(ex.value) and cred["password"] not in str(ex.value)

    # client commands and variables in a statement are never the client's: they reach the server as SQL
    for evil in ("\\! touch /tmp/pwned", "system touch /tmp/pwned", ":!! touch /tmp/pwned", "\\! touch /tmp/pwned\n"):
        try:
            run(server, evil)
        except D.DbError:
            pass
    assert _docker("exec", name, "ls", "/tmp/pwned", check=False).returncode != 0
    sa = run(server, "SELECT '$(MSSQL_SA_PASSWORD)' AS v")
    assert sa["rows"][0][0] == "$(MSSQL_SA_PASSWORD)"

    # caps: at most max_rows rows, at most 1 MB of output
    many = {"postgres": "SELECT g FROM generate_series(1, 2000) AS g",
            "mysql": "WITH RECURSIVE g(n) AS (SELECT 1 UNION ALL SELECT n + 1 FROM g WHERE n < 900) SELECT a.n FROM g a CROSS JOIN g b LIMIT 2000",
            "sqlserver": "SELECT TOP (2000) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS n FROM sys.all_columns a CROSS JOIN sys.all_columns b"}[engine]
    capped = run(server, many, max_rows=500)
    assert len(capped["rows"]) == 500 and capped["truncated"]
    big = {"postgres": "SELECT repeat('x', 3000000) AS v", "mysql": "SELECT REPEAT('x', 3000000) AS v",
           "sqlserver": "SELECT REPLICATE(CAST(N'x' AS nvarchar(max)), 3000000) AS v"}[engine]
    with pytest.raises(D.DbError) as ex:
        run(server, big)
    assert "1 MB" in str(ex.value)

    if engine == "sqlserver":            # what cannot be captured falls back to sqlcmd's text
        res = run(server, "CREATE TABLE #t (a int); INSERT #t VALUES (42); SELECT a FROM #t")
        assert res["kind"] == "text" and "42" in res["text"]

    # the password was never on a command line
    assert seen and not any(cred["password"] in " ".join(a) for a in seen)


def test_timeout(server, monkeypatch):
    engine = server[0]
    monkeypatch.setattr(D, "STATEMENT_TIMEOUT", 2)
    slow = {"postgres": "SELECT pg_sleep(10)", "mysql": "SELECT SLEEP(10) FROM (SELECT 1) t",
            "sqlserver": "WAITFOR DELAY '00:00:10'"}[engine]
    t0 = time.time()
    try:
        res = run(server, slow)
        assert engine == "mysql" and res["kind"] == "rows"     # max_execution_time ends a SELECT early: SLEEP returns 1
    except D.DbError as ex:
        assert "timeout" in str(ex).lower() or "cancel" in str(ex).lower() or "expired" in str(ex).lower(), str(ex)
    assert time.time() - t0 < 9


def test_drop_and_provision_again(server):
    engine, name, target, runner, _, cred = server
    db = L.db_name(NS)
    p = _admin(engine, name, D.drop_script(engine, db))
    assert p.returncode == 0, p.stderr + p.stdout
    with pytest.raises(D.DbError):
        run(server, "SELECT 1 AS one")
    p = _admin(engine, name, L.provision_sql(engine, NS, cred))      # what the lab agent's reconcile runs
    assert p.returncode == 0, p.stderr + p.stdout
    assert run(server, "SELECT 1 AS one")["rows"] == [["1"]]
    assert run(server, D.tables_sql(engine))["rows"] == []
